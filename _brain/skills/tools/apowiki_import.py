#!/usr/bin/env python3
"""Replay cached ApoWiki revisions as git commits, preserving authorship.

This is a faithful history TRANSCRIPTION, not a fabrication: every commit
carries the real contributor's name, the real edit timestamp, and the
MediaWiki revision id it came from, so any claim in this repository can be
traced back to the exact revision that introduced it. That is also what
satisfies the GFDL's attribution requirement by construction rather than by a
blanket credits page.

Two rules it enforces mechanically:

* **No bare IP addresses.** Early ApoWiki edits are authored by IP rather
  than by a registered name. An IP is personal data under GDPR and this
  repository is public, so IP authors are pseudonymised to a stable
  `ApoWiki-anonymous-<n>` identity. The mapping from pseudonym to real IP is
  written ONLY to a local, gitignored provenance sidecar. Registered usernames
  are kept as-is: those are pseudonyms their owners chose.
* **Wikitext is stored unconverted.** What ApoWiki published is what lands in
  raw/apowiki-export/, with the GFDL notice the contract requires.

Commits are ordered by timestamp across ALL articles, so the resulting history
reads like the wiki's actual life rather than article-by-article.

Usage:
    python3 apowiki_import.py --cache _temp/apowiki-cache --repo . [--dry-run]
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import os
import subprocess
import urllib.parse
from pathlib import Path

GFDL_NOTICE = """<!--
Source: ApoWiki (https://apowiki.fi) — article "{title}", MediaWiki revision {revid}.
Permalink: https://apowiki.fi/index.php?oldid={revid}
Licence: GNU Free Documentation License, version 1.3 or later (GFDL-1.3-or-later).
This file is the original wikitext, stored unconverted. Do not edit by hand:
it is regenerated by skills/tools/apowiki_import.py from the ApoWiki export.
-->
"""


def is_bare_ip(name: str) -> bool:
    try:
        ipaddress.ip_address(name.strip())
        return True
    except ValueError:
        return False


def slug(title: str) -> str:
    """A kebab-case, filesystem-safe name that still reads as the article."""
    out = []
    for ch in title.lower():
        if ch.isalnum():
            out.append(ch)
        elif ch in " _-/":
            out.append("-")
        # Finnish letters survive .isalnum(); punctuation is dropped
    s = "".join(out)
    while "--" in s:
        s = s.replace("--", "-")
    return s.strip("-") or "untitled"


def git(repo: Path, *args: str, env: dict | None = None) -> str:
    e = dict(os.environ)
    if env:
        e.update(env)
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True,
                       text=True, env=e)
    if r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout


def resolve_filenames(cache: Path) -> dict[str, str]:
    """Map each article title to a UNIQUE export filename.

    Slugging is lossy: ApoWiki has distinct titles that reduce to the same
    slug — '"Jumala ei ole kiva"' and 'Jumala ei ole kiva', 'A.D. 30' and
    'AD 30', 'C. S. Lewis' and 'C S Lewis'. 38 slugs collide across 848 pages.
    Letting them share a filename would make one article silently overwrite
    another and corrupt both histories into one interleaved file.

    Colliding titles are disambiguated by appending a short, stable suffix
    derived from the title itself, so the mapping never depends on iteration
    order. The first title in sorted order keeps the bare slug, which keeps
    the common case readable; the rest get `-v2`, `-v3`, which stays
    kebab-case as raw/'s naming rule requires.
    """
    titles = []
    for f in sorted(cache.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        if d.get("revisions"):
            titles.append(d["title"])

    groups: dict[str, list[str]] = {}
    for t in sorted(titles):
        groups.setdefault(slug(t), []).append(t)

    names: dict[str, str] = {}
    for base, group in groups.items():
        if len(group) == 1:
            names[group[0]] = base
            continue
        for i, t in enumerate(group):
            # `-v2` rather than `--2`: a double hyphen is not kebab-case and
            # the raw/ contract rejects it, rightly — one style, no exceptions.
            names[t] = base if i == 0 else f"{base}-v{i + 1}"
    return names


def load_revisions(cache: Path) -> list[dict]:
    """Every revision from every cached article, flattened and time-ordered."""
    revs = []
    for f in sorted(cache.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        for r in d["revisions"]:
            text = (r.get("slots", {}).get("main", {}) or {}).get("*")
            if text is None:
                continue  # deleted/suppressed revision content
            revs.append({
                "title": d["title"], "revid": r["revid"],
                "timestamp": r["timestamp"], "user": r.get("user", ""),
                "comment": (r.get("comment") or "").strip(),
                "text": text,
            })
    revs.sort(key=lambda r: (r["timestamp"], r["revid"]))
    return revs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache", required=True, type=Path)
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--out", default="_brain/raw/apowiki-export",
                    help="bundle-relative export directory")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()

    repo = args.repo.resolve()
    outdir = repo / args.out
    names = resolve_filenames(args.cache)
    dupes = sum(1 for n in names.values() if "--" in n)
    if dupes:
        print(f"{dupes} titles disambiguated (distinct articles sharing a slug)", flush=True)
    revs = load_revisions(args.cache)
    if args.limit:
        revs = revs[:args.limit]
    print(f"{len(revs)} revisions to replay", flush=True)

    # Stable pseudonyms, assigned in first-appearance order so a re-run of the
    # same cache produces the same identities.
    ip_map: dict[str, str] = {}
    for r in revs:
        if is_bare_ip(r["user"]) and r["user"] not in ip_map:
            ip_map[r["user"]] = f"ApoWiki-anonymous-{len(ip_map) + 1}"
    print(f"{len(ip_map)} distinct IP authors pseudonymised", flush=True)

    if args.dry_run:
        print("\n-- first 5 commits that would be made --")
        for r in revs[:5]:
            who = ip_map.get(r["user"], r["user"]) or "ApoWiki-unknown"
            print(f"  {r['timestamp']}  {who:28} {r['title'][:40]} (rev {r['revid']})")
        return 0

    outdir.mkdir(parents=True, exist_ok=True)
    provenance = repo / ".provenance"
    provenance.mkdir(exist_ok=True)

    for i, r in enumerate(revs, 1):
        author = ip_map.get(r["user"], r["user"]) or "ApoWiki-unknown"
        # A synthetic, non-routable address: never a real person's mailbox.
        email = f"{slug(author)}@apowiki.invalid"
        path = outdir / f"{names[r['title']]}.wiki"
        path.write_text(
            GFDL_NOTICE.format(title=r["title"], revid=r["revid"]) + r["text"],
            encoding="utf-8")

        summary = r["comment"] or f"Edit {r['title']}"
        summary = summary.splitlines()[0][:72]
        message = (
            f"{summary}\n\n"
            f"ApoWiki article: {r['title']}\n"
            f"MediaWiki revision: {r['revid']}\n"
            f"Permalink: https://apowiki.fi/index.php?oldid={r['revid']}\n"
            f"Licence: GFDL-1.3-or-later\n"
        )
        git(repo, "add", str(path.relative_to(repo)))
        if not git(repo, "diff", "--cached", "--name-only").strip():
            continue  # identical content: a null edit in the wiki
        env = {
            "GIT_AUTHOR_NAME": author, "GIT_AUTHOR_EMAIL": email,
            "GIT_AUTHOR_DATE": r["timestamp"],
            "GIT_COMMITTER_NAME": author, "GIT_COMMITTER_EMAIL": email,
            "GIT_COMMITTER_DATE": r["timestamp"],
        }
        git(repo, "commit", "--no-verify", "-m", message, env=env)
        if i % 100 == 0:
            print(f"  {i}/{len(revs)} commits", flush=True)

    if ip_map:
        (provenance / "apowiki-ip-authors.json").write_text(
            json.dumps({"_comment": "PERSONAL DATA (GDPR). Never commit. "
                                    "Maps public pseudonyms to the IP addresses "
                                    "behind early ApoWiki edits.",
                        "map": ip_map}, indent=1, ensure_ascii=False),
            encoding="utf-8")
        print(f"provenance sidecar written to {provenance} (gitignored)", flush=True)
    print("import complete", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
