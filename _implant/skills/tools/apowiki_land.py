#!/usr/bin/env python3
"""Land reviewed English translations in knowledge/en/ and keep their links true.

An English page keeps the Finnish page's file name, one folder over:
knowledge/articles/x.md -> knowledge/en/x.md. Both folders sit at the same
depth, so links to ../topics/, ../books/ and ../glossary/ work unchanged.
Only article-to-article links need a decision, and this tool makes it:

* a link to an article that has an English page points at that page (x.md)
* a link to an article that has none yet points at the Finnish page
  (../articles/x.md), so it lands now and is upgraded by a later run

The tool is idempotent: run it after every batch and every earlier English
page is re-pointed at the pages that batch added. The Finnish pages are not
touched: knowledge/articles/ is regenerated by the converter, and each
English page already names its source in `translated_from:`.

Each landed page also gets American spelling (apowiki_american.py), per
conventions/american-english.md.

Usage:
    python3 apowiki_land.py [_temp/translations/x.md ...]   # copy in, then fix links
    python3 apowiki_land.py --selftest
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]          # _implant/
ARTICLES = ROOT / "knowledge" / "articles"
EN = ROOT / "knowledge" / "en"

LINK = re.compile(r"\]\((?:\.\./articles/)?([^)/#\s]+)\.md(#[^)\s]*)?\)")
# A red link the converter kept (label, maybe a Wikipedia fallback, and the
# greppable comment). When a page written later in knowledge/pages/ answers
# it, the Finnish article picks that up on the next convert, but a landed
# English page would not: it is a copy. So landing re-points those too.
# (A red link kept as plain text has no delimited label, so it is left for
# the reviewer; the converter links those itself in the Finnish page.)
RED = re.compile(r"\[([^\]]*)\]\([^)\s]*\) <!-- red link: ([^>]*?) -->")


def written_pages() -> dict[str, str]:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from apowiki_convert import WRITTEN_PAGES  # one parser for aliases
    return WRITTEN_PAGES


def relink_red(text: str, pages: dict[str, str]) -> str:
    def repl(m: re.Match) -> str:
        page = pages.get(m.group(2).replace("_", " ").strip().lower())
        return f"[{m.group(1)}](../pages/{page}.md)" if page else m.group(0)
    return RED.sub(repl, text)


def relink(text: str, have_en: set[str], have_fi: set[str]) -> str:
    def repl(m: re.Match) -> str:
        stem, frag = m.group(1), m.group(2) or ""
        if stem in have_en:
            return f"]({stem}.md{frag})"
        if stem in have_fi:
            return f"](../articles/{stem}.md{frag})"
        return m.group(0)
    return LINK.sub(repl, text)


def _front(p: Path) -> dict[str, str]:
    m = re.match(r"^---\n(.*?)\n---\n", p.read_text(encoding="utf-8"), re.S)
    out = {}
    for line in (m.group(1) if m else "").splitlines():
        k, _, v = line.partition(":")
        out[k.strip()] = v.strip().strip('"').replace('\\"', '"')
    return out


def write_index(stems: set[str]) -> None:
    """knowledge/en/index.md: generated, frontmatter-free (OKF reserved)."""
    rows = []
    for s in sorted(stems):
        f = _front(EN / f"{s}.md")
        rows.append(f"* [{f.get('title', s)}]({s}.md) — {f.get('description', '')}"
                    f" *({f.get('translation_status', 'machine')}; Finnish: "
                    f"[{s}](../articles/{s}.md))*")
    (EN / "index.md").write_text(
        "# English\n\n"
        "English translations of the ApoWiki articles, one page per article "
        "under the Finnish page's file name. Generated by "
        "`skills/tools/apowiki_land.py`; the procedure is "
        "[Translate an article](../../skills/translate-an-article.md). "
        "The Finnish page stays the source of truth.\n\n"
        + "\n".join(rows) + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    if argv[:1] == ["--selftest"]:
        return selftest()
    EN.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from apowiki_american import convert_file   # US spelling (conventions/)
    for a in argv:
        src = Path(a)
        dst = EN / src.name
        shutil.copyfile(src, dst)
        old, new = convert_file(dst)
        if new != old:
            dst.write_text(new, encoding="utf-8")
        print(f"landed {src.name}" + (" (American spelling applied)" if new != old else ""))
    have_en = {p.stem for p in EN.glob("*.md") if p.name != "index.md"}
    have_fi = {p.stem for p in ARTICLES.glob("*.md")}
    pages = written_pages()
    changed = 0
    for p in sorted(EN.glob("*.md")):
        if p.name == "index.md":
            continue
        t = p.read_text(encoding="utf-8")
        n = relink_red(relink(t, have_en, have_fi), pages)
        if n != t:
            p.write_text(n, encoding="utf-8")
            changed += 1
    write_index(have_en)
    print(f"{len(have_en)} English pages, {changed} relinked")
    return 0


def selftest() -> int:
    t = "See [a](x.md), [b](y.md#s), [c](../articles/x.md) and [d](../topics/t.md)."
    out = relink(t, {"x"}, {"x", "y"})
    assert out == ("See [a](x.md), [b](../articles/y.md#s), [c](x.md) "
                   "and [d](../topics/t.md)."), out
    t = ("[P](https://fi.wikipedia.org/wiki/P) <!-- red link: P -->, "
         "[Q](https://fi.wikipedia.org/wiki/Q) <!-- red link: Q -->")
    out = relink_red(t, {"p": "p-page"})
    assert out == ("[P](../pages/p-page.md), "
                   "[Q](https://fi.wikipedia.org/wiki/Q) <!-- red link: Q -->"), out
    print("apowiki_land: selftest ok")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
