#!/usr/bin/env python3
"""ApoWiki's official glossary (ApoWiki:Sanasto) -> raw source + implant page.

ApoWiki keeps one official Finnish glossary, `ApoWiki:Sanasto`: 415 terms,
each written as `{{sana|term|definition 1|definition 2|...}}`. The wiki's
own rule, stated at the top of the page, is that articles use terms in the
glossary's sense. A definition wrapped in `<s>…</s>` (struck through) is
common usage that ApoWiki articles should *not* use. Articles link a term as
`[[AW:S#term|label]]`, and there are 415 such links across the corpus.

The glossary matters twice:

* **Links.** The converter used to drop those 415 links, because the main
  fetch covered only the main namespace. With the glossary page present they
  land on `knowledge/glossary/sanasto.md#<anchor>`.
* **Translation.** A term's meaning in ApoWiki is fixed by this page, so a
  translator (human or model) must render each term the same way every
  time. The English column is the translation contract; see
  skills/translate-an-article.md. This tool never invents English. It only
  keeps whatever English renderings are already recorded in
  knowledge/glossary/english.md, and lists which terms still lack one.

Three outputs, all regenerated on every run:

1. `raw/apowiki-project/sanasto.wiki`: the page's wikitext, unconverted, with
   the GFDL notice and the oldid permalink (the same form as
   raw/apowiki-export/).
2. `knowledge/glossary/sanasto.md`: every term under its own heading, with
   an explicit anchor, its definitions, and struck-through definitions
   marked as usage ApoWiki avoids.
3. `knowledge/glossary/index.md`: frontmatter-free, per OKF.

Usage:
    python3 apowiki_glossary.py --fetch        # download the page into _temp/
    python3 apowiki_glossary.py                # regenerate from _temp/ or raw/
    python3 apowiki_glossary.py --selftest
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://apowiki.fi/api.php"
UA = "brain-implant-apologetics/0.1 (faithful GFDL history import; contact via repository)"
TITLE = "ApoWiki:Sanasto"
# The generated pages change when the raw glossary or english.md changes.
# english.md is edited by hand and bumped by its editor, so the generated
# pages take the later of its timestamp and the raw import's.
TIMESTAMP = "2026-09-27T12:00:00Z"

CACHE = Path("_temp/apowiki-project/sanasto.json")
RAW = Path("_implant/raw/apowiki-project/sanasto.wiki")
OUT = Path("_implant/knowledge/glossary")
ENGLISH = OUT / "english.md"

NOTICE = """<!--
Source: ApoWiki (https://apowiki.fi) — page "{title}", MediaWiki revision {revid}.
Permalink: https://apowiki.fi/index.php?oldid={revid}
Authors: https://apowiki.fi/index.php?title=ApoWiki:Sanasto&action=history
Licence: GNU Free Documentation License, version 1.3 or later (GFDL-1.3-or-later).
This file is the original wikitext, stored unconverted. Do not edit by hand:
it is regenerated by skills/tools/apowiki_glossary.py.
-->
"""


# ---------------------------------------------------------------------------
# Anchors. MediaWiki encodes spaces in a fragment as "_" and punctuation as
# ".XX" (for example "(" becomes ".28"). The converter receives the fragment
# as written in the article, so the anchor both sides agree on is a slug of
# the *decoded* term: lower case, letters and digits kept (ä, ö and å
# included), everything else a single hyphen.
# ---------------------------------------------------------------------------

def decode_fragment(frag: str) -> str:
    frag = frag.replace("_", " ")
    frag = re.sub(r"\.([0-9A-F]{2})", lambda m: chr(int(m.group(1), 16)), frag)
    return frag.strip()


def anchor(term: str) -> str:
    term = term.strip("*'")
    term = unicodedata.normalize("NFC", decode_fragment(term).lower())
    out = []
    for ch in term:
        out.append(ch if ch.isalnum() else "-")
    s = re.sub(r"-{2,}", "-", "".join(out)).strip("-")
    return s or "termi"


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------

def split_top(body: str) -> list[str]:
    """Split on `|` that sits outside nested [[…]] and {{…}}."""
    parts, depth, cur, i = [], 0, [], 0
    while i < len(body):
        two = body[i:i + 2]
        if two in ("[[", "{{"):
            depth += 1
            cur.append(two)
            i += 2
            continue
        if two in ("]]", "}}") and depth:
            depth -= 1
            cur.append(two)
            i += 2
            continue
        if body[i] == "|" and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(body[i])
        i += 1
    parts.append("".join(cur))
    return parts


def entries(wikitext: str) -> list[tuple[str, list[str]]]:
    """Every `{{sana|…}}`, in page order, even when it spans lines."""
    out, i = [], 0
    while True:
        s = wikitext.find("{{sana|", i)
        if s < 0:
            return out
        depth, j = 0, s
        while j < len(wikitext):
            if wikitext.startswith("{{", j):
                depth += 1
                j += 2
            elif wikitext.startswith("}}", j):
                depth -= 1
                j += 2
                if depth == 0:
                    break
            else:
                j += 1
        parts = split_top(wikitext[s + 2:j - 2])[1:]
        term = re.sub(r"\s+", " ", parts[0]).strip() if parts else ""
        italic = term.startswith("''") and term.endswith("''")
        term = term.strip("'").strip()
        if italic:
            term = f"*{term}*"
        defs = [re.sub(r"\s+", " ", p).strip() for p in parts[1:]]
        if term:
            out.append((term, [d for d in defs if d]))
        i = j


def inline(text: str, terms: set[str]) -> str:
    """Wikitext of one definition -> markdown, links landing in-page."""

    def wl(m: re.Match) -> str:
        inner = m.group(1)
        tgt, _, lbl = inner.partition("|")
        lbl = (lbl or tgt.lstrip("#").split(":", 1)[-1]) \
            + (m.group(2) or "")  # MediaWiki link trail
        tgt = tgt.strip()
        if tgt.startswith("#"):
            a = anchor(tgt[1:])
            return f"[{lbl}](#{a})" if a in terms else lbl
        if tgt.lower().startswith(("wp:", "w:")):
            page = tgt.split(":", 1)[1].strip().replace(" ", "_")
            return f"[{lbl}](https://fi.wikipedia.org/wiki/{page})"
        return lbl  # main-namespace article: see the note on the page

    text = re.sub(r"\[\[([^\[\]]+)\]\]([^\W\d_]+)?", wl, text)
    text = re.sub(r"\{\{rp\|([^}]+)\}\}", r"\1", text)
    text = re.sub(r"\{\{[^{}]*\}\}", "", text)
    text = re.sub(r"<sup>(.*?)</sup>", r"^\1", text)
    text = re.sub(r"'''(.+?)'''", r"**\1**", text)
    text = re.sub(r"''(.+?)''", r"*\1*", text)
    return text.strip()


# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------

def stamp() -> str:
    m = re.search(r"^timestamp: (\S+)", ENGLISH.read_text(encoding="utf-8")
                  if ENGLISH.exists() else "", re.M)
    return max(TIMESTAMP, m.group(1)) if m else TIMESTAMP


def load_english() -> dict[str, str]:
    """anchor -> English, from the `| term | English | note |` table in
    english.md. That page is edited by hand (it records decisions), so this
    tool only reads it and never rewrites it."""
    if not ENGLISH.exists():
        return {}
    out = {}
    for line in ENGLISH.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or not line.lstrip().startswith("|"):
            continue
        fi, en = cells[0], cells[1]
        if not fi or not en or fi.lower() in ("term", "termi") or set(fi) <= set("-: "):
            continue
        out[anchor(fi)] = en.strip("*")
    return out


def render(ents: list[tuple[str, list[str]]], revid: str) -> str:
    terms = {anchor(t) for t, _ in ents}
    english = load_english()
    lines = [
        "---",
        "type: glossary",
        "about: apologetics",
        'title: "Sanasto — ApoWikin virallinen sanasto"',
        'description: "ApoWiki\'s official Finnish glossary: '
        f'{len(terms)} terms with the definitions ApoWiki articles use them in, '
        "struck-through senses marked as usage ApoWiki avoids. The fixed term "
        'list for translation."',
        "tags: [apowiki, glossary, sanasto, terminology, translation]",
        f"timestamp: {stamp()}",
        "half_life: 0",
        "---",
        NOTICE.format(title=TITLE, revid=revid).replace(
            "This file is the original wikitext, stored unconverted. Do not edit by hand:\n"
            "it is regenerated by skills/tools/apowiki_glossary.py.",
            "Converted from raw/apowiki-project/sanasto.wiki by "
            "skills/tools/apowiki_glossary.py. Do not edit by hand."),
        "# Sanasto",
        "",
        "ApoWiki's official glossary, converted from "
        f"[{TITLE}](https://apowiki.fi/index.php?oldid={revid}). "
        "In ApoWiki's own words, its articles should use terms in the senses "
        "given here, and an article that departs from them must say so. A "
        "sense marked *(ApoWiki avoids this sense)* was struck through on the "
        "original page: it is common usage, but ApoWiki's articles are not "
        "meant to use it.",
        "",
        "Articles link here as `sanasto.md#<term>`. The English rendering "
        "under a term, where present, comes from "
        "[English renderings](english.md). It is the translation contract that "
        "[Translate an article](../../skills/translate-an-article.md) "
        "follows. A term without one has no fixed English yet.",
        "",
    ]
    # The page lists a few terms twice (e.g. "älykkään suunnitelman
    # teoria"). One anchor per term: merge their definitions, keep order.
    merged: dict[str, tuple[str, list[str]]] = {}
    for term, defs in ents:
        a = anchor(term)
        if a in merged:
            merged[a][1].extend(d for d in defs if d not in merged[a][1])
        else:
            merged[a] = (term, list(defs))
    letter = None
    for term, defs in sorted(merged.values(),
                             key=lambda e: e[0].strip("*").lower()):
        first = term.strip("*")[0].upper()
        if first != letter:
            letter = first
            lines += [f"## {letter}", ""]
        a = anchor(term)
        lines += [f'<a id="{a}"></a>', "", f"### {term}", ""]
        if a in english:
            lines += [f"English: **{english[a]}**", ""]
        for d in defs:
            struck = re.fullmatch(r"(?:'')?<s>(.*)</s>(?:'')?", d) or \
                re.fullmatch(r"<s>(.*)</s>", d)
            if struck:
                lines.append(f"- ~~{inline(struck.group(1), terms)}~~ "
                             "*(ApoWiki avoids this sense)*")
            else:
                lines.append(f"- {inline(d, terms)}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def index_page(n: int, missing_en: int) -> str:
    return f"""# Glossary

ApoWiki's own terminology, kept apart from the articles because it has a
different job: it fixes what a word *means* here.

* [Sanasto](sanasto.md) — ApoWiki's official Finnish glossary, {n} terms.
  Articles link a term as `sanasto.md#<term>`.
* [English renderings](english.md) — the fixed English rendering of each term: the
  translation contract. {n - missing_en} of {n} terms have one so far.
"""


# ---------------------------------------------------------------------------

def fetch() -> None:
    q = urllib.parse.urlencode({
        "action": "query", "format": "json", "titles": TITLE,
        "prop": "revisions", "rvprop": "content|ids|timestamp",
        "rvslots": "main"})
    req = urllib.request.Request(f"{API}?{q}", headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=90) as r:
        data = json.load(r)
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    print(f"fetched {TITLE} -> {CACHE}")


def source() -> tuple[str, str]:
    """(wikitext, revid) from the fetch cache, else from the committed raw."""
    if CACHE.exists():
        page = next(iter(json.loads(CACHE.read_text(encoding="utf-8"))
                         ["query"]["pages"].values()))
        rev = page["revisions"][-1]
        slots = rev.get("slots", {}).get("main", {})
        return slots.get("*") or rev.get("*", ""), str(rev["revid"])
    text = RAW.read_text(encoding="utf-8")
    revid = re.search(r"oldid=(\d+)", text).group(1)
    return re.sub(r"^<!--.*?-->\n", "", text, flags=re.S), revid


def selftest() -> int:
    assert anchor("uusi organismi .28avioliitto.29") == "uusi-organismi-avioliitto"
    assert anchor("a_priori") == "a-priori"
    assert anchor("Äärinaturalismi") == "äärinaturalismi"
    assert entries("{{sana|''a priori''|ennalta}}") == [("*a priori*", ["ennalta"])]
    assert anchor("*a priori*") == "a-priori"
    e = entries("{{sana|ad hoc|[[#hypoteesi|hyp]]|x}}\n{{sana|b|y\nz}}")
    assert e == [("ad hoc", ["[[#hypoteesi|hyp]]", "x"]), ("b", ["y z"])], e
    assert inline("[[#hypoteesi|hyp]]", {"hypoteesi"}) == "[hyp](#hypoteesi)"
    assert inline("[[#puuttuu|p]]", set()) == "p"
    assert inline("[[#naturalismi]]n", {"naturalismi"}) == "[naturalismin](#naturalismi)"
    print("apowiki_glossary: selftest ok")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fetch", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    if args.fetch:
        fetch()
    wikitext, revid = source()
    RAW.parent.mkdir(parents=True, exist_ok=True)
    RAW.write_text(NOTICE.format(title=TITLE, revid=revid) + wikitext,
                   encoding="utf-8")
    ents = entries(wikitext)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "sanasto.md").write_text(render(ents, revid), encoding="utf-8")
    english = load_english()
    terms = {anchor(t) for t, _ in ents}
    missing = len(terms - set(english))
    unknown = sorted(set(english) - terms)
    if unknown:
        print(f"english.md names terms the glossary lacks: {unknown}")
    (OUT / "index.md").write_text(index_page(len(terms), missing),
                                  encoding="utf-8")
    print(f"{len(terms)} terms; {len(terms) - missing} with English; "
          f"revision {revid}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
